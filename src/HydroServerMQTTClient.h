/**
 * @file HydroServerMQTTClient.h
 * @author Sabin Panta
 * @brief MQTT client that publishes sensor measurements to a broker.
 *
 * Part of the HydroServerArduinoClient library
 */

#ifndef SRC_HYDROSERVERMQTTCLIENT_H_
#define SRC_HYDROSERVERMQTTCLIENT_H_

#include "PublisherUtil.h"
#include <Arduino.h>
#include <ArduinoMqttClient.h>

/**
 * @brief Publishes observations to an MQTT broker
 *
 * Observations are published to
 * `siteCode/clientId/sensorId/observedProperty`, so call setSiteCode() and
 * setClientID() before connecting. The payload is the same SensorThings JSON
 * that HydroServerHTTPClient sends.
 *
 * The broker only relays messages. To get them into HydroServer you need a
 * separate service that subscribes to the broker and writes the observations
 * to HydroServer.
 *
 * @code
 * WiFiClient wifiClient;
 * HydroServerMQTTClient mqttClient(wifiClient, "test.mosquitto.org");
 *
 * void setup() {
 *   // ...join Wi-Fi and set the clock first
 *   mqttClient.setSiteCode("mysite");
 *   mqttClient.setClientID("logger01");
 *   mqttClient.setLastWill("offline");
 *   mqttClient.connectToBroker();
 * }
 *
 * void loop() {
 *   mqttClient.poll();
 *   // ...when it's time for a reading:
 *   mqttClient.publishObservation(temperature, getISO8601Time());
 * }
 * @endcode
 *
 * @ingroup clients
 */
class HydroServerMQTTClient {
public:
  static constexpr uint16_t defaultPort = 1883;

  /**
   * @brief Creates a client for a known broker.
   * This constructor can be initalized using client and broker host ip or
   * address.
   *
   * @param client Network client to use, such as `WiFiClient` or
   * `*modem.createClient()`.
   * @param broker Broker host name or IP address.
   * @param port Broker port. Defaults to 1883.
   * @param clientId Name the broker knows this logger by. Also the second
   * part of every topic.
   * @param username Broker user name, if it needs one.
   * @param password Broker password. Can be an empty string for brokers that
   * accept a user name on its own.
   */
  HydroServerMQTTClient(Client &client, const char *broker,
                        uint16_t port = defaultPort,
                        const char *clientId = nullptr,
                        const char *username = nullptr,
                        const char *password = nullptr);

  /**
   * @brief Creates a client before the broker is known.
   *
   * Give the broker later through the long form of connectToBroker().
   *
   * @param client Network client to use.
   */
  HydroServerMQTTClient(Client &client);

  /**
   * @brief Sets the site code for MQTT topics
   *
   * Use your HydroServer site's code (see [managing site
   * metadata](https://hydroserver.org/user-guides/how-to/managing-site-metadata.html#managing-site-metadata)).
   * Call this before setLastWill() and connectToBroker().
   *
   * @param siteCode The site code.
   */
  void setSiteCode(const char *siteCode);

  /**
   * @brief Sets the broker username and password.
   *
   * This setter can be used if you initialized the class without any parameter
   *
   * @param username Username.
   * @param password Password. May be empty, but not null.
   */
  void setAuthentication(const char *username, const char *password);

  /**
   * @brief Sets the client ID. This is also part of MQTT topic.
   *
   * Give each logger its own ID.
   *
   * @param clientId The client ID.
   */
  void setClientID(const char *clientId);

  /**
   * @brief Sets mqtt connect config for mqtt publish and lwt.
   *
   * By default qos will be 0 and dup flag is set to false.
   * Use this setter before you connect to broker
   *
   * @param retain If retain is true, the message published in the topic will
   * remain until it get replaced with new message
   * @param qos set qos to either 0 or 1. This library doesn't support qos 2
   * @param dup set duplicate flag in mqtt connect.
   *
   */
  void setMqttConnectConfig(bool retain, uint8_t qos = 1, bool dup = false);

  /**
   * @brief Sets the last will message
   *
   * The message goes to `siteCode/clientId/lwt`, so call setSiteCode() and
   * setClientID() first, and call this before connecting to broker. QoS 1 is
   * recommended for lwt.
   *
   * @param payload This includes the payload that is part of lwt message.
   * @return 1 on success, 0 on failure.
   */
  int setLastWill(const char *payload);

  /**
   * @brief Get the lwt topic. The topic for lwt is generated by the library.
   * The user can call this to know what the lwt topic is.
   * @param payload This includes the payload that is part of lwt message.
   * @return topic.
   */

  const char *getLastWillTopic() const;

  /**
   * @brief Sets whether the MQTT client starts a clean session.
   *
   * When set to true, the broker starts a clean session by discarding
   * any existing session state associated with this client ID. The
   * broker does not retain the client's subscriptions or queued messages
   * after the client disconnects.
   *
   * When set to false, the broker creates or resumes a persistent session.
   * The broker retains the client's subscriptions and queues eligible
   * QoS 1 and QoS 2 messages while the client is disconnected. The client
   * must reconnect using the same client ID to resume the session.
   *
   * For QoS 0 messages, the broker does not guarantee message delivery
   * while the client is disconnected.
   *
   * @param cleanSession `true` to start a clean session; `false` to
   *                     resume or create a persistent session.
   */
  void setCleanSession(bool cleanSession);

  /**
   * @brief Sets the MQTT keep-alive interval in seconds.
   *
   * The client must send a control packet within this interval.
   * If the broker receives no packet within 1.5 times this interval,
   * it may disconnect the client. If your logger sleeps between
   * readings, increase the interval or reconnect after waking.
   *
   * @param seconds Keep-alive interval in seconds (default: 60 seconds).
   */
  void setKeepAliveInterval(unsigned long seconds);

  /**
   * @brief Sets how long to wait for the broker when
   * connecting.
   *
   * The default is 20 seconds.
   *
   * @param seconds Timeout in seconds.
   */
  void setConnectionTimeout(unsigned long seconds);

  /**
   * @brief Connects to an MQTT broker using the specified address and port.
   *
   * Optionally updates the client ID, username, and password.
   * If these values are not included, they either remain null or they take
   * value set by the setter functions.
   *
   * @param broker Broker hostname or IP address.
   * @param port Broker port (default: defaultPort).
   * @param clientId MQTT client identifier (optional).
   * @param username Broker username (optional).
   * @param password Broker password (optional).
   * @return 1 if connected successfully; 0 otherwise.
   *         Use getConnectionError() to retrieve the connection error.
   */
  bool connectToBroker(const char *broker, uint16_t port = defaultPort,
                       const char *clientId = nullptr,
                       const char *username = nullptr,
                       const char *password = nullptr);

  /**
   * @brief Connects to the broker using previously configured settings.
   *
   * Returns false if no broker has been configured or the connection fails.
   * Use getConnectionError() to retrieve the connection error.
   *
   * @return true if connected; false otherwise.
   */
  bool connectToBroker();

  /// @return `true` while the connection to the broker is open.
  bool isConnected();

  /**
   * @brief Returns the error code from the last connection attempt.
   *
   * Error codes are defined by ArduinoMqttClient. Negative values
   * indicate network errors, while positive values indicate broker
   * connection errors.
   *
   * @return Error code, or 0 if the connection succeeded.
   */
  int getConnectionError();

  /**
   * @brief Subscribes to a topic under the configured site.
   *
   * The configured site code is added to the beginning of the topic.
   * Subscriptions use QoS 0.
   *
   * @param topic Topic to subscribe to.
   * @return 1 on success, 0 if not connected or subscription fails.
   */
  int subscribe(const char *topic);

  /**
   * @brief Reads the incoming message as SensorThings JSON and saves its
   * `result`.
   *
   * Call this from your onMessage() handler, then read the value with
   * getLatestValueofTopic(). This consumes the message, so don't also call
   * readMessage() for the same one.
   */
  void deserializePayload();

  /**
   * @brief Returns the value deserializePayload() saved for a topic.
   *
   * The site code is added in front of @p topic, the same way as in
   * subscribe().
   *
   * @param topic Topic without the site code.
   * @return The saved value. Only meaningful if the latest message arrived
   * on this topic.
   */
  float getLatestValueofTopic(const char *topic);

  /**
   * @brief Stops listening on a topic.
   *
   * Unlike subscribe(), this doesn't add the site code, so pass the full
   * topic.
   *
   * @param topic Full topic, including the site code.
   * @return 1 on success, 0 on failure.
   */
  int unsubscribe(const char *topic);

  /**
   * @brief Processes incoming MQTT messages and maintains the connection.
   *
   * Call this regularly in loop() to receive messages and handle
   * MQTT keep-alive communication.
   */
  void poll();

  /**
   * @brief Sets a function to run when a message arrives on a subscribed
   * topic.
   *
   * The function gets the message size in bytes. Inside it, messageTopic()
   * tells you where the message came from, and readMessage() or
   * deserializePayload() reads it.
   *
   * @code
   * void handleMessage(int size) {
   *   Serial.print(mqttClient.messageTopic());
   *   Serial.print(": ");
   *   Serial.println(mqttClient.readMessage());
   * }
   *
   * mqttClient.onMessage(handleMessage);
   * @endcode
   *
   * @param callback Function to call for each message.
   */
  void onMessage(void (*callback)(int));

  /// @brief Reads the incoming message.
  /// @return The message as text.
  String readMessage();

  /// @return The topic the incoming message arrived on.
  String messageTopic();

  /**
   * @brief Publishes one observation.
   *
   * The topic is built from the site code, the clientid, sensorid and observed
   * property.
   *
   * @param observation The reading to send.
   * @param phenomenonTime Time of measurement in UTC
   * @return 1 on success, 0 if not connected or sending failed.
   */
  int publishObservation(const Observation &observation,
                         const char *phenomenonTime);

  /**
   * @brief Returns the MQTT topic for an observation.
   *
   * The topic follows the format:
   * siteCode/clientId/sensorId/observedProperty
   *
   * @param observation Observation used to determine the topic.
   * @return Full MQTT topic.
   */
  const char *getObservationTopic(const Observation &observation);

  /**
   * @brief Publishes several observations with the same timestamp.
   *
   * @param observations Array of pointers to the observations to send.
   * @param size Number of entries in @p observations.
   * @param phenomenonTime Timestamp in UTC.
   * @return each succesful publish return 1. Therefore, a succesful publish
   * means the value is equal to size of the observation array .
   */
  uint8_t publishAll(Observation **observations, uint8_t size,
                     const char *phenomenonTime) {
    uint8_t published = 0;
    for (uint8_t i = 0; i < size; i++) {
      if (publishObservation(*observations[i], phenomenonTime)) {
        published++;
      }
    }
    return published;
  }

private:
  MqttClient _mqttClient;
  const char *_broker;
  uint16_t _port;
  const char *_clientId;
  void setdefaultclientid();
  const char *_username;
  const char *_password;
  unsigned long _keepAliveSeconds = 60;
  unsigned long _connectionTimeout = 20;
  bool _cleanSession = false;
  uint8_t _qos = 1;
  bool _retain = true;
  bool _dup = false;
  const char *_sitecode = "river";
  float _latestValue;
  char _observationTopic[256];
  char _lastWillTopic[128];
};

#endif
